let lang = localStorage.getItem('pf-lang') || ((navigator.language || 'de').startsWith('tr') ? 'tr' : 'de');

export function getLang() { return lang; }
export function setLang(l) { lang = l; localStorage.setItem('pf-lang', l); applyI18n(); }
export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.de[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); });
}
